class ChartCanvas(tk.Canvas):
    """Draws a `plots.Chart`, and redraws itself when the window resizes."""

    def __init__(self, parent, **kw):
        super().__init__(parent, background="white", highlightthickness=0,
                         **kw)
        self.chart: Optional[plots.Chart] = None
        self._retries = 0
        self.bind("<Configure>", lambda e: self.redraw())

    def _retry(self) -> None:
        if self._retries < 3:
            self._retries += 1
            self.redraw()

    def show(self, chart: Optional[plots.Chart]) -> None:
        self.chart = chart
        self.redraw()

    def redraw(self) -> None:
        self.delete("all")
        w, h = self.winfo_width(), self.winfo_height()
        if w < 60 or h < 60:
            # The tab this canvas lives on has not been laid out yet, so
            # there is nothing to draw into.  Switching to the tab fires
            # <Configure> and brings us back here; the idle retry covers
            # the case where it does not.
            self.after_idle(self._retry)
            return
        ch = self.chart
        if ch is None:
            self.create_text(w // 2, h // 2, text="Evaluate a design first",
                             fill="#999", font=BODY)
            return
        self._retries = 0
        m = plots.Mapper(ch, w, h)
        self.create_text(w // 2, 16, text=ch.title, font=HEAD, fill="#222")

        # ---- grid and ticks ----
        xt = plots.nice_ticks(m.x0, m.x1)
        yt = plots.nice_ticks(m.y0, m.y1)
        xstep = (xt[1] - xt[0]) if len(xt) > 1 else 1.0
        ystep = (yt[1] - yt[0]) if len(yt) > 1 else 1.0
        for t in xt:
            x = m.px(t)
            self.create_line(x, m.top, x, m.bottom, fill="#ecf0f4")
            self.create_text(x, m.bottom + 12,
                             text=plots.tick_label(t, xstep),
                             font=("Segoe UI", 8), fill="#555")
        for t in yt:
            y = m.py(t)
            self.create_line(m.left, y, m.right, y, fill="#ecf0f4")
            self.create_text(m.left - 6, y, text=plots.tick_label(t, ystep),
                             anchor="e", font=("Segoe UI", 8), fill="#555")
        self.create_rectangle(m.left, m.top, m.right, m.bottom,
                              outline="#b9c2cc")
        self.create_text((m.left + m.right) // 2, m.bottom + 30,
                         text=ch.x_label, font=BODY, fill="#333")
        self.create_text(14, (m.top + m.bottom) // 2, text=ch.y_label,
                         angle=90, font=BODY, fill="#333")

        # ---- horizontal rules ----
        for value, label, colour in ch.h_lines:
            if not (m.y0 <= value <= m.y1):
                continue
            y = m.py(value)
            self.create_line(m.left, y, m.right, y, fill=colour,
                             dash=(3, 3), width=1)
            self.create_text(m.right - 4, y - 7, text=label, anchor="e",
                             font=("Segoe UI", 8), fill=colour)

        # ---- series ----
        for s in ch.series:
            pts = m.points(s.xs, s.ys)
            if len(pts) >= 4:
                self.create_line(*pts, fill=s.colour, width=s.width,
                                 dash=s.dash or None, smooth=False)

        # ---- legend, top-left inside the frame ----
        ly = m.top + 8
        for s in ch.series:
            self.create_line(m.left + 10, ly, m.left + 34, ly,
                             fill=s.colour, width=s.width,
                             dash=s.dash or None)
            self.create_text(m.left + 40, ly, text=s.label, anchor="w",
                             font=("Segoe UI", 8), fill="#333")
            ly += 14
        if ch.footnote:
            self.create_text(m.left, h - 6, text=ch.footnote, anchor="w",
                             font=("Segoe UI", 8), fill="#777")


class ThreeViewCanvas(tk.Canvas):
    """Plan and side views, drawn to a common scale with a metre rule."""

    def __init__(self, parent, **kw):
        super().__init__(parent, background="white", highlightthickness=0,
                         **kw)
        self.data: Optional[Tuple] = None
        self.span_in = 0.0
        self.length_in = 0.0
        self._retries = 0
        self.bind("<Configure>", lambda e: self.redraw())

    def _retry(self) -> None:
        if self._retries < 3:
            self._retries += 1
            self.redraw()

    def show(self, ac) -> None:
        self.data = plots.three_view(ac) if ac is not None else None
        self.span_in = ac.wing.span_m * 39.3701 if ac is not None else 0.0
        self.length_in = (ac.body.fuse_length_m * 39.3701
                          if ac is not None else 0.0)
        self.redraw()

    def _dim_h(self, y: float, x0: float, x1: float, text: str) -> None:
        """A horizontal dimension line with ticks and a centred label."""
        self.create_line(x0, y, x1, y, fill="#888", arrow="both")
        for x in (x0, x1):
            self.create_line(x, y - 4, x, y + 4, fill="#888")
        self.create_text((x0 + x1) / 2, y + 10, text=text,
                         font=("Segoe UI", 8), fill="#666")

    def _dim_v(self, x: float, y0: float, y1: float, text: str) -> None:
        self.create_line(x, y0, x, y1, fill="#888", arrow="both")
        for y in (y0, y1):
            self.create_line(x - 4, y, x + 4, y, fill="#888")
        self.create_text(x - 8, (y0 + y1) / 2, text=text, angle=90,
                         font=("Segoe UI", 8), fill="#666")

    def redraw(self) -> None:
        self.delete("all")
        w, h = self.winfo_width(), self.winfo_height()
        if w < 80 or h < 80:
            self.after_idle(self._retry)
            return
        if self.data is None:
            self.create_text(w // 2, h // 2, text="Evaluate a design first",
                             fill="#999", font=BODY)
            return
        self._retries = 0
        plan, side, _ext = self.data
        pad = 26
        panel_h = (h - 3 * pad) // 2

        def extent(shapes):
            xs = [p[0] for s in shapes for p in s.points]
            ys = [p[1] for s in shapes for p in s.points]
            return min(xs), max(xs), min(ys), max(ys)

        # one scale for both views, so they are comparable
        scales = []
        for shapes, ph in ((plan, panel_h), (side, panel_h)):
            x0, x1, y0, y1 = extent(shapes)
            scales.append(min((w - 2 * pad) / max(x1 - x0, 1e-6),
                              ph / max(y1 - y0, 1e-6)))
        scale = min(scales) * 0.92

        for idx, (shapes, title) in enumerate(((plan, "PLAN"),
                                               (side, "SIDE"))):
            x0, x1, y0, y1 = extent(shapes)
            oy = pad + idx * (panel_h + pad)
            cx = pad + ((w - 2 * pad) - (x1 - x0) * scale) / 2
            cy = oy + (panel_h - (y1 - y0) * scale) / 2
            self.create_text(pad, oy - 10, text=title, anchor="w",
                             font=("Segoe UI", 8, "bold"), fill="#666")
            for sh in shapes:
                pts = []
                for px, py in sh.points:
                    pts.extend((cx + (px - x0) * scale,
                                cy + (py - y0) * scale))
                if len(pts) < 4:
                    continue
                if sh.fill and len(pts) >= 6:
                    self.create_polygon(*pts, fill=sh.fill,
                                        outline=sh.outline, width=sh.width)
                else:
                    self.create_line(*pts, fill=sh.outline, width=sh.width)

        # ---- dimension callouts on the plan view ----
        x0p, x1p, y0p, y1p = extent(plan)
        oy = pad
        cxp = pad + ((w - 2 * pad) - (x1p - x0p) * scale) / 2
        cyp = oy + (panel_h - (y1p - y0p) * scale) / 2
        self._dim_v(cxp - 10, cyp, cyp + (y1p - y0p) * scale,
                    "span %.0f in" % (self.span_in or 0))
        self._dim_h(cyp + (y1p - y0p) * scale + 12,
                    cxp, cxp + (x1p - x0p) * scale,
                    "length %.0f in" % (self.length_in or 0))

        # scale bar
        bar_m = 0.5
        while bar_m * scale > (w - 2 * pad) * 0.35:
            bar_m *= 0.5
        bx, by = pad, h - 10
        self.create_line(bx, by, bx + bar_m * scale, by, fill="#333", width=2)
        self.create_line(bx, by - 4, bx, by + 4, fill="#333")
        self.create_line(bx + bar_m * scale, by - 4,
                         bx + bar_m * scale, by + 4, fill="#333")
        self.create_text(bx + bar_m * scale + 8, by,
                         text="%.2f m  (%.1f in)" % (bar_m, bar_m * 39.3701),
                         anchor="w", font=("Segoe UI", 8), fill="#333")


