    @staticmethod
    def _opening_design() -> Dict[str, Any]:
        """The design the window opens on.

        Read from examples/optimised_v1.json when it is there, so the GUI
        opens on whatever the last search actually recommended.  Hard
        coding it here means the opening state silently becomes a stale
        claim about what a good aeroplane looks like: these defaults were
        the optimum before the rules pass, and they were not the optimum
        after it.
        """
        fallback = {"airfoil": "SD7062", "span_m": 1.55, "aspect_ratio": 5.74,
                    "taper": 1.0, "motor": "COBRA_C4120_12",
                    "prop": "APC_12x8", "n_motors": 1,
                    "pack": "GA_6S3300_60C", "n_systems": 1,
                    "sensor_mass_kg": 0.9, "n_simulators": 3,
                    "sensor_m3_kg": 0.9, "drop_height_in": 60}
        here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        path = os.path.join(here, "examples", "optimised_v1.json")
        try:
            with open(path, encoding="utf-8") as fh:
                d = json.load(fh)
        except (OSError, ValueError):
            return fallback
        out = dict(fallback)
        out["_from_file"] = True
        out.update({k: v for k, v in d.items() if k in fallback})
        if d.get("chord_m"):
            out["aspect_ratio"] = d["span_m"] / d["chord_m"]
        if not d.get("sensor_m3_kg"):
            out["sensor_m3_kg"] = d.get("sensor_mass_kg", 0.9)
        return out

