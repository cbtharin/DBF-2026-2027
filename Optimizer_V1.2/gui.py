"""Desktop front end: change a number, see what it does to the aeroplane.

    python -m dbf2027.gui          or      python dbf_gui.py

Tkinter only, because tkinter ships with Python and the rest of this
project has no dependencies either.  The charts are drawn on a plain
Canvas from the geometry in `plots.py`; there is no matplotlib.

Layout
------
Left is input, split three ways on purpose:

  * **Setup** - which design is under test, in what weather, scored
    against what.  There are no design FIELDS here.  The aeroplane is a
    single piece of state that a search or `Load...` sets, named by a
    one-line caption that also says where it came from.  An earlier
    version had the full design form here and the Report tab restated
    every one of its thirteen values, which meant the same numbers in two
    places with nothing saying which was authoritative.
  * **Search space** - the ranges `Run search` explores, and the only
    design input on the left.  These were hard-coded in `DesignSpace`
    and unreachable, so a search silently ignored the form.
  * **Advanced** - every remaining number in `Rules`, `Course` and
    `BuildStandard`, generated by walking those dataclasses.  Because it
    is generated, a field added to the model shows up here automatically
    rather than being quietly unreachable.

Right is output, and it is the only place the design is read back: the
full dossier, a dimensions table, the charts, a scale three-view, the
scoring arithmetic, the rules matrix and the function catalogue.

Threading
---------
Evaluating one design takes ~100 ms, which is fast enough to do inline.
A search takes minutes, so it runs on a worker thread and reports back
through a queue that the Tk main loop polls.  Tk is not thread-safe, so
**the worker never touches a widget** - it only puts text on the queue.
"""
