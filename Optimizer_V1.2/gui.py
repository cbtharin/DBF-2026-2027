    def _spec(self):
        return CATALOGUES_BY_KEY[self.cat_kind.get()]

    def _select_catalogue(self, label: str) -> None:
        for c in CATALOGUES:
            if c.label == label:
                self.cat_kind.set(c.key)
                break
        spec = self._spec()
        # Keep the dropdown in step when the selection is made in code
        # rather than by clicking: otherwise the label and the table
        # disagree, which is exactly the kind of quiet lie this project
        # has been stripping out elsewhere.
        if self.cat_combo.get() != spec.label:
            self.cat_combo.set(spec.label)
        self.cat_note.configure(text=spec.note)
        cols = spec.fieldnames()
        self.cat_tree.configure(columns=cols)
        for c in cols:
            self.cat_tree.heading(c, text=c)
            self.cat_tree.column(c, width=max(62, min(150, 8 * len(c) + 44)),
                                 anchor="w", stretch=False)
        # rebuild the form for this catalogue's columns
        for w in self.cat_form_frame.winfo_children():
            w.destroy()
        self.cat_fields = {}
        for i, col in enumerate(spec.columns):
            r, c = divmod(i, 2)
            holder = ttk.Frame(self.cat_form_frame)
            holder.grid(row=r, column=c, sticky="ew", padx=4)
            self.cat_form_frame.columnconfigure(c, weight=1)
            self.cat_fields[col.name] = Field(holder, 0, col.name,
                                              col.default, col.kind,
                                              col.help, width=14)
            holder.columnconfigure(1, weight=1)
        self._refresh_catalogue()

    def _refresh_catalogue(self) -> None:
        spec = self._spec()
        self.cat_tree.delete(*self.cat_tree.get_children())
        n_user = 0
        for ident in sorted(spec.store):
            row = spec.to_row(spec.store[ident])
            vals = []
            for c in spec.fieldnames():
                v = row.get(c, "")
                vals.append("%.6g" % v if isinstance(v, float) else v)
            user = is_user_entry(spec.key, ident)
            n_user += bool(user)
            self.cat_tree.insert("", "end", iid=ident, values=vals,
                                 tags=("user",) if user else ())
        self.cat_status.configure(
            text="%d entries, %d of them yours (tinted)"
                 % (len(spec.store), n_user))

    def _catalogue_row_selected(self) -> None:
        sel = self.cat_tree.selection()
        if sel:
            self._fill_catalogue_form(sel[0])

    def _fill_catalogue_form(self, ident: Optional[str]) -> None:
        spec = self._spec()
        if ident is None:
            for col in spec.columns:
                self.cat_fields[col.name].set(col.default)
            return
        row = spec.to_row(spec.store[ident])
        for col in spec.columns:
            self.cat_fields[col.name].set(row.get(col.name, col.default))

    def _add_catalogue_entry(self) -> None:
        spec = self._spec()
        try:
            row = {name: fld.get() for name, fld in self.cat_fields.items()}
        except ValueError as exc:
            self.cat_status.configure(text="bad value: %s" % exc)
            return
        ident = str(row.get("key") or row.get("name") or "").strip()
        if not ident:
            self.cat_status.configure(
                text="give it a key" if "key" in self.cat_fields
                else "give it a name")
            return
        if not is_user_entry(spec.key, ident) and ident in spec.store:
            if not messagebox.askyesno(
                    "Override a built-in?",
                    "%s is a built-in %s. Your version will be used "
                    "instead, for every command, until you delete it.\n\n"
                    "Continue?" % (ident, spec.singular)):
                return
        try:
            path = add_user_entry(spec.key, row)
        except Exception as exc:
            messagebox.showerror("Could not add", str(exc))
            return
        self._refresh_catalogue()
        self.cat_tree.selection_set(ident)
        self.cat_status.configure(text="saved %s to %s"
                                       % (ident, os.path.basename(path)))
        self.status.set("%s '%s' saved - it is available to Evaluate and "
                        "to a search straight away" % (spec.singular, ident))

    def _delete_catalogue_entry(self) -> None:
        sel = self.cat_tree.selection()
        if not sel:
            self.cat_status.configure(text="select a row first")
            return
        spec, ident = self._spec(), sel[0]
        if not is_user_entry(spec.key, ident):
            self.cat_status.configure(
                text="%s is built in - only your own entries can be "
                     "deleted" % ident)
            return
        if not messagebox.askyesno("Delete", "Remove %s from %s.csv?"
                                   % (ident, spec.key)):
            return
        remove_user_entry(spec.key, ident)
        self._refresh_catalogue()
        self.cat_status.configure(text="deleted %s" % ident)

    def _reload_catalogues(self) -> None:
        counts = reload_catalogues()
