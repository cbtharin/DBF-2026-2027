def capture(fn: Callable, *args, **kw) -> str:
    """Run something that prints, and give back what it printed."""
    buf = io.StringIO()
    with redirect_stdout(buf):
        fn(*args, **kw)
    return buf.getvalue()


class Field:
    """One labelled entry box bound to a value of a known type."""

    def __init__(self, parent, row: int, label: str, value: Any,
                 kind: type, tip: str = "", width: int = 12):
        self.kind = kind
        self.name = label
        ttk.Label(parent, text=label, font=BODY).grid(
            row=row, column=0, sticky="w", padx=(6, 4), pady=1)
        self.var = tk.StringVar(value=self._fmt(value))
        e = ttk.Entry(parent, textvariable=self.var, width=width, font=BODY)
        e.grid(row=row, column=1, sticky="ew", padx=(0, 6), pady=1)
        self.entry = e
        if tip:
            ttk.Label(parent, text=tip, font=("Segoe UI", 8),
                      foreground="#666").grid(row=row, column=2, sticky="w",
                                              padx=(0, 6))

    @staticmethod
    def _fmt(v: Any) -> str:
        if isinstance(v, float):
            if v != v or v in (float("inf"), float("-inf")):
                return str(v)
            return ("%.6g" % v)
        return str(v)

    def get(self) -> Any:
        raw = self.var.get().strip()
        if self.kind is bool:
            return raw.lower() in ("1", "true", "yes", "on")
        if self.kind is int:
            return int(float(raw))
        if self.kind is float:
            return float(raw)
        return raw

    def set(self, v: Any) -> None:
        self.var.set(self._fmt(v))


class Combo:
    """A labelled read-only dropdown."""

    def __init__(self, parent, row: int, label: str, values: List[str],
                 value: str, width: int = 22):
        ttk.Label(parent, text=label, font=BODY).grid(
            row=row, column=0, sticky="w", padx=(6, 4), pady=1)
        self.var = tk.StringVar(value=value)
        cb = ttk.Combobox(parent, textvariable=self.var, values=values,
                          state="readonly", width=width, font=BODY)
        cb.grid(row=row, column=1, columnspan=2, sticky="ew",
                padx=(0, 6), pady=1)
        self.widget = cb

    def get(self) -> str:
        return self.var.get()

    def set(self, v: str) -> None:
        self.var.set(v)


