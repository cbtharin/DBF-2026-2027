    def _sync_density(self) -> None:
        """Recompute density from elevation and temperature."""
        try:
            env = Environment.at_density_altitude(
                self.f_alt.get(), self.f_temp.get(), self.f_wind.get())
        except ValueError:
            self.rho_note.configure(text="")
            return
        self.f_rho.set(round(env.rho, 4))
        self._update_density_note()

    def _update_density_note(self) -> None:
        try:
            rho = self.f_rho.get()
        except ValueError:
            self.rho_note.configure(text="")
            return
        env = Environment(rho=rho)
        self.rho_note.configure(
            text="= %.0f ft density altitude, %.1f%% of sea-level ISA"
                 % (env.density_altitude_ft, 100.0 * rho / 1.225))

    def read_config(self) -> Config:
        cfg = Config()
        env = Environment.at_density_altitude(
            self.f_alt.get(), self.f_temp.get(), self.f_wind.get())
        # Viscosity still comes from the temperature - it barely depends
        # on density - but the density itself is whatever the box says,
        # so a measured value overrides the ISA estimate.
        try:
            env = Environment(rho=self.f_rho.get(), nu=env.nu,
                              wind_mps=env.wind_mps,
                              field_elev_m=env.field_elev_m)
        except ValueError:
            pass
        cfg.env = env
        for (owner, name), fld in self.adv.items():
            setattr(getattr(cfg, owner), name, fld.get())
        cfg.rules.normalisation = self.f_norm.get()
        cfg.rules.field_best_m2_lb_per_s = self.f_fm2.get()
        cfg.rules.field_best_m3_lap_lb = self.f_fm3.get()
        cfg.rules.field_best_gm_lb_in = self.f_fmg.get()
        return cfg

    def read_design(self) -> Design:
        """The design under test.

        Held as state rather than read back out of widgets: there are no
        design widgets any more.
        """
        if self.design is None:
            raise ValueError("no design loaded - run a search or Load one")
        return self.design

