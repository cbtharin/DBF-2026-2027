    def read_space(self) -> DesignSpace:
        """Build the DesignSpace the search will actually use."""
        def ints(text, fallback):
            out = []
            for part in str(text).split(","):
                part = part.strip()
                if part:
                    try:
                        out.append(int(float(part)))
                    except ValueError:
                        pass
            return out or fallback

        sp = DesignSpace()
        sp.span_bounds = (self.sp_span_lo.get(), self.sp_span_hi.get())
        sp.ar_bounds = (self.sp_ar_lo.get(), self.sp_ar_hi.get())
        sp.taper_bounds = (self.sp_taper_lo.get(), self.sp_taper_hi.get())
        sp.sensor_bounds = (self.sp_sensor_lo.get(), self.sp_sensor_hi.get())
        sp.m3_frac_bounds = (self.sp_m3_lo.get(), self.sp_m3_hi.get())
        sp.drop_height_bounds = (self.sp_drop_lo.get(), self.sp_drop_hi.get())
        sp.motor_counts = ints(self.sp_motors.get(), [1, 2])
        sp.system_counts = ints(self.sp_systems.get(), [1, 2])
        return sp

    def reset_search_space(self) -> None:
        sp, rr = DesignSpace(), Config().rules
        for fld, val in ((self.sp_span_lo, sp.span_bounds[0]),
                         (self.sp_span_hi, sp.span_bounds[1]),
                         (self.sp_ar_lo, sp.ar_bounds[0]),
                         (self.sp_ar_hi, sp.ar_bounds[1]),
                         (self.sp_taper_lo, sp.taper_bounds[0]),
                         (self.sp_taper_hi, sp.taper_bounds[1]),
                         (self.sp_sensor_lo, rr.sensor_mass_min_kg),
                         (self.sp_sensor_hi, rr.sensor_mass_max_kg),
                         (self.sp_m3_lo, sp.m3_frac_bounds[0]),
                         (self.sp_m3_hi, sp.m3_frac_bounds[1]),
                         (self.sp_drop_lo, sp.drop_height_bounds[0]),
                         (self.sp_drop_hi, sp.drop_height_bounds[1])):
            fld.set(val)
        self.sp_motors.set(",".join(str(v) for v in sp.motor_counts))
        self.sp_systems.set(",".join(str(v) for v in sp.system_counts))
        self.status.set("search space reset to defaults")

